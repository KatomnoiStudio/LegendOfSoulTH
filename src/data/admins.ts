/*
  ห้ามใส่อีเมลจริงของใครตรงนี้อีก

  ค่านี้ถูก build ลง bundle เป็นข้อความเปล่า ๆ แล้วขึ้นเว็บสาธารณะ เดิมเป็น Gmail จริงของ
  เจ้าของโปรเจกต์ ซึ่งไม่ได้ทำให้ประตูแน่นขึ้นเลย (ดูหัวไฟล์) แต่ทำให้ที่อยู่ส่วนตัวไปอยู่
  ในที่ที่สแปมบอตกวาดได้ — เสียของฟรี ๆ โดยไม่ได้อะไรกลับมา

  `.invalid` เป็น TLD ที่ RFC 6761 สงวนไว้ไม่ให้ resolve ได้เลย จึงไม่มีทางชนกับกล่องจดหมาย
  จริงของใคร และอ่านแล้วรู้ทันทีว่าไม่ใช่ที่อยู่จริง กลไกไม่เปลี่ยน: สมัครบัญชีด้วยสตริงนี้
  แล้วจะได้สิทธิ์ผู้ดูแล (`EMAIL_PATTERN` ตรวจแค่รูปแบบ เกมไม่เคยส่งอีเมลอยู่แล้ว)

  ตัดสินผ่าน ask CB 4 ที่นั่ง 2026-08-07 — ทั้งสี่เห็นตรงกันว่าไม่ควรทำ hash หรือ env var:
  hash ค่าที่ผู้ใช้พิมพ์เองตอนล็อกอินและเดาได้ง่ายไม่ได้กันอะไร ส่วน env var ของ Vite ก็ถูก
  inline ลง bundle เหมือนกันเป๊ะ ต่างกันแค่ดูเหมือนของลับ ซึ่งแย่กว่าเพราะหลอกคนอ่าน
*/
const ADMIN_EMAILS: readonly string[] = ['admin@legendofsoulth.invalid']

/** เทียบแบบไม่สนตัวพิมพ์เล็กใหญ่/ช่องว่างหัวท้าย ให้ตรงกับที่ accountRepository เก็บอีเมล */
export function isAdminEmail(email: string | null | undefined): boolean {
  if (!email) return false
  const normalized = email.trim().toLowerCase()
  return ADMIN_EMAILS.includes(normalized)
}
